def active(steps):
    return bool(steps and steps[0].get('response_policy') == POLICY)


def attach(question, labels):
    return {**question, 'options': options(labels.split('|')), 'response_policy': POLICY, 'hint': HINT}


def early(question, topic, index):
    return attach(question, EARLY[topic][index])


def interview(question, topic, band, index):
    return attach(question, INTERVIEWS[topic][band][index])


def probe(step, steps):
    if not step or not active(steps):
        return step
    result = copy.deepcopy(step)
    for i, q in enumerate(result['questions']):
        labels = FACET_PROBES.get(q.get('facet'), PROBES[q['focus']])
        if q['id'] == 'follow-context' and q['focus'] == 'boundary' and q.get('facet') != 'responsibility':
            q['text'] = '回看刚才那件事，你决定如何回应时最在意什么？'
        if q['id'] == 'follow-context' and q['focus'] == 'execution' and not q.get('facet'):
            q['text'] = '回看刚才那件事，什么最影响你要不要开始或继续？'
        result['questions'][i] = attach(q, labels)
    return result


def selected(question, answer):
    """Resolve IDs against the stored question; never trust client label text."""
    return next((item for item in question.get('options', []) if item['id'] == answer.get('choice')), None)


def analysis_selection(question, answer):
    item = selected(question, answer)
    return item if item and item['id'] not in {'unsure', 'other'} else None
